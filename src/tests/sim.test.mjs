test('a torpedo searches the datum until the seeker cone finds the submarine', async () => {
  const w = new SimWorld({ seed: 4, catalog: cat });
  w.noEndCheck = true;
  const perry = await cat.vessel('usn_ffg_oliver_hazard_perry', 'Variant18');
  const subSpec = await cat.vessel('usn_ssn_sturgeon');
  subSpec.kind = 'sub';
  const ship = w.addUnit({ spec: perry, team: 1, x: 0, y: 0, ai: false });
  const sub = w.addUnit({ spec: subSpec, team: 2, x: 0, y: 3 * NM, z: -40, ai: false });
  const torpId = Object.keys(ship.ammo).find((id) => ship.spec.ammoSpecs[id]?.type === 'Torpedo');
  const shipAmmo = ship.spec.ammoSpecs[torpId];
  assert.equal(shipAmmo.searchMode, 1, 'ship Mk46 snakes');
  assert.equal(shipAmmo.snakeDeg, 30);
  const air = await cat.ammo('usn_mk46_mod5_air');
  assert.equal(air.searchMode, 2, 'air Mk46 circles');
  assert.equal(air.circleDps, 5);
  assert.equal(air.searchKt, 45);
  // 6 nm needs the 8 nm / 30 kt setting. 3 nm still fits the 5 nm / 45 kt setting.
  const far = w.addUnit({ spec: subSpec, team: 2, x: 0, y: 6 * NM, z: -40, ai: false });
  w.fire(ship, torpId, far);
  w.step(4.45);
  const slow = [...w.units.values()].find((u) => u.kind === 'torpedo' && u.targetId === far.id);
  assert.ok(Math.abs(slow.transitKt - 30) < 0.05, 'the run setting is 30 knots');
  assert.ok(Math.abs(slow.speed / KT - 60) < 0.1, 'the tube exit is 60 knots until it is under');
  slow.alive = false;
  ship.cooldown = 0;
  assert.equal(w.fire(ship, torpId, sub), true);
  const snake = [...w.units.values()].find((u) => u.kind === 'torpedo' && u.alive && u.targetId === sub.id);
  // The datum stays where the boat was. Moving it clear of the nose cone leaves the search running.
  sub.x = -1.2 * NM;
  for (let i = 0; i < 120 && dist2(snake, snake.aim) > 1.15 * NM; i++) w.step(2);
  for (let i = 0; i < 120 && !snake.searching; i++) w.step(0.5);
  assert.equal(snake.searching, true);
  const hp = sub.hp;
  const t0 = snake.snakeT;
  w.step(1.5);
  const expect = shipAmmo.snakeDeg * Math.sin(Math.PI * 2 * (t0 + 1.5) / shipAmmo.snakeCycle);
  assert.ok(Math.abs(wrap180(snake.heading - snake.searchHdg) - expect) < 1.5);
  assert.equal(sub.hp, hp);
  const circle = w._launchTorpedo(ship, air, sub);
  circle.aim = { x: 0, y: 3 * NM, z: -40 };
  circle.lastKnown = { ...circle.aim };
  circle.x = 0; circle.y = 0; circle.heading = 0; circle.searchHdg = 0; circle.reached = false; circle.searching = false;
  for (let i = 0; i < 120 && dist2(circle, circle.aim) > 1.15 * NM; i++) w.step(2);
  for (let i = 0; i < 120 && !circle.searching; i++) w.step(0.5);
  assert.equal(circle.searching, true);
  const c0 = circle.circle;
  w.step(10);
  assert.ok(circle.circle - c0 > 49 && circle.circle - c0 < 51, 'circle search is 5 deg/s');
  assert.equal(sub.hp, hp);
  const spiral = { ...air, searchMode: 3, spiralRadiusNm: 0.5, searchKt: 45, turnRate: 10 };
  const spin = w._launchTorpedo(ship, spiral, sub);
  spin.x = circle.x; spin.y = circle.y; spin.z = circle.z; spin.heading = 0; spin.reached = true; spin.searching = true;
  const h0 = spin.heading;
  w.step(10);
  const turned = wrap180(spin.heading - h0);
  assert.ok(turned > 13 && turned < 16, 'spiral turn is search speed over the search radius');
  assert.ok(spin.z < circle.z, 'the spiral dives toward the floor');
});

