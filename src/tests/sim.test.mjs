test('a tracking radar corrects the solution halfway, and a dark optical gun does not', async () => {
  const w = new SimWorld({ seed: 1, catalog: cat });
  w.noEndCheck = true;
  const perry = await cat.vessel('usn_ffg_oliver_hazard_perry', 'Variant18');
  const drone = await cat.vessel('usn_septar_qst-35');
  const gun = perry.ammoSpecs['usn_cal_76mm'];
  const ship = w.addUnit({ spec: perry, team: 1, x: 0, y: 0, heading: 0, ai: false });
  const held = w.addUnit({ spec: drone, team: 2, x: 4000, y: 0, ai: false });
  const gunW = perry.weapons.find((wpn) => wpn.ammo.some((a) => a.id === gun.id));
  w._fireShell(ship, gun, held);
  const shell = [...w.units.values()].find((u) => u.kind === 'shell');
  assert.ok(Math.abs(shell.spotAt - shell.tof / 2) < 1e-6);
  const st = ship._fc[`${gunW.idx}:${held.id}`];
  st.next = 1000;
  const opened = st.solution;
  w.step(shell.tof * 0.4);
  assert.equal(st.solution, opened);
  w.step(shell.tof * 0.2);
  const bumped = st.solution - opened;
  assert.ok(bumped >= 0.1 && bumped <= 0.15, `halfway correction ${bumped}`);
  w.step(shell.tof);
  assert.equal(st.solution, opened + bumped);
  const night = new SimWorld({ seed: 1, catalog: cat });
  night.noEndCheck = true;
  night.weather.sun = 0;
  const blind = night.addUnit({ spec: perry, team: 1, x: 0, y: 0, heading: 0, ai: false });
  blind.spec = { ...perry, weapons: perry.weapons.map((wpn) => (wpn === gunW ? { ...wpn, directors: [] } : wpn)) };
  const tgt = night.addUnit({ spec: drone, team: 2, x: 4000, y: 0, ai: false });
  night._fireShell(blind, gun, tgt);
  const dark = blind._fc[`${gunW.idx}:${tgt.id}`];
  dark.next = 1000;
  const before = dark.solution;
  night.step(5);
  assert.equal(dark.solution, before);
});

